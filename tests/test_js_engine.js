/**
 * Test JS Inference Engine Against PyTorch Reference
 */

"use strict";

const fs = require("fs");
const path = require("path");
const assert = require("assert");

const { MeshPartitionA, MeshPartitionB, MeshFullModel } = require("../engine/inference_engine");

const WEIGHTS_DIR = path.join(__dirname, "..", "room-server", "public", "weights");

function runTest() {
  console.log("======================================================================");
  console.log("TESTING JAVASCRIPT INFERENCE ENGINE AGAINST PYTORCH REFERENCE");
  console.log("======================================================================");

  // 1. Load manifest and binary weights
  const manifestPath = path.join(WEIGHTS_DIR, "weights_manifest.json");
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf-8"));
  console.log(`Loaded weights manifest: ${manifest.total_parameters.toLocaleString()} parameters.`);

  const partABuf = fs.readFileSync(path.join(WEIGHTS_DIR, "partition_a.bin"));
  const partBBuf = fs.readFileSync(path.join(WEIGHTS_DIR, "partition_b.bin"));
  console.log(`Loaded partition_a.bin: ${(partABuf.length / 1024 / 1024).toFixed(2)} MB`);
  console.log(`Loaded partition_b.bin: ${(partBBuf.length / 1024 / 1024).toFixed(2)} MB`);

  // Convert Node Buffers to ArrayBuffers
  const abA = partABuf.buffer.slice(partABuf.byteOffset, partABuf.byteOffset + partABuf.byteLength);
  const abB = partBBuf.buffer.slice(partBBuf.byteOffset, partBBuf.byteOffset + partBBuf.byteLength);

  // 2. Instantiate Partition A and Partition B
  const engineA = MeshPartitionA.fromBuffer(abA, manifest);
  const engineB = MeshPartitionB.fromBuffer(abB, manifest);
  console.log("Instantiated MeshPartitionA and MeshPartitionB successfully.");

  // 3. Test Prompt: "MESH distributed inference test" -> expected next byte 179
  const promptStr = "MESH distributed inference test";
  const promptBytes = Array.from(Buffer.from(promptStr, "utf-8"));
  console.log(`\nInput prompt: "${promptStr}" (${promptBytes.length} bytes)`);

  const t0 = performance.now();
  const act = engineA.forward(promptBytes);
  const t1 = performance.now();
  console.log(`Phone A execution time: ${(t1 - t0).toFixed(2)} ms. Intermediate activation elements: ${act.length}`);
  assert.equal(act.length, promptBytes.length * 384, "Activation shape mismatch");

  const t2 = performance.now();
  const result = engineB.forward(act, promptBytes.length);
  const t3 = performance.now();
  console.log(`Phone B execution time: ${(t3 - t2).toFixed(2)} ms. Selected next byte: ${result.nextByte} (repr: '${String.fromCharCode(result.nextByte)}')`);

  // PyTorch reference generated next byte 179
  assert.equal(result.nextByte, 179, `Expected byte 179, got ${result.nextByte}`);
  console.log("✓ Next token MATCHES PyTorch reference (179) exactly!");

  // 4. Test Autoregressive Generation for prompt "MESH"
  const promptShort = Array.from(Buffer.from("MESH", "utf-8"));
  console.log(`\nTesting 10-step autoregressive generation on prompt "MESH": ${JSON.stringify(promptShort)}`);

  // Expected sequence from PyTorch verify_reference: [77, 69, 83, 72, 228, 228, 228, 228, 228, 228, 98, 98, 240, 98]
  const expectedTokens = [77, 69, 83, 72, 228, 228, 228, 228, 228, 228, 98, 98, 240, 98];

  const currentTokens = [...promptShort];
  for (let step = 0; step < 10; step++) {
    const s0 = performance.now();
    const activations = engineA.forward(currentTokens);
    const s1 = performance.now();
    const { nextByte } = engineB.forward(activations, currentTokens.length);
    const s2 = performance.now();

    currentTokens.push(nextByte);
    console.log(`  Step ${step + 1}: Generated byte ${nextByte} | Phone A: ${(s1 - s0).toFixed(1)}ms | Phone B: ${(s2 - s1).toFixed(1)}ms | Total: ${(s2 - s0).toFixed(1)}ms`);
    assert.equal(nextByte, expectedTokens[4 + step], `Mismatch at step ${step + 1}: expected ${expectedTokens[4 + step]}, got ${nextByte}`);
  }

  console.log("\nGenerated sequence: " + JSON.stringify(currentTokens));
  assert.deepEqual(currentTokens, expectedTokens, "Autoregressive generation mismatch!");
  console.log("✓ 10-step distributed autoregressive generation matches PyTorch BIT-FOR-BIT across all steps!");
  console.log("======================================================================");
  console.log("ALL JS ENGINE TESTS PASSED SUCCESSFULLY!");
  console.log("======================================================================");
}

runTest();
